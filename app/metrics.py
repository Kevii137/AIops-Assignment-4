import os
import sys
import threading
import time

import psutil
from prometheus_client import Counter, Enum, Gauge, Histogram, Info, Summary, disable_created_metrics, start_http_server

disable_created_metrics()

METRICS_PORT = int(os.environ.get("METRICS_PORT", "18000"))
CLIENT_LABELS = ["mode", "client_ip", "session_id", "browser"]

# counters
images_processed = Counter("caption_images_processed_total", "Images captioned, per client", CLIENT_LABELS)
requests_total = Counter("caption_requests_total", "Requests (one image or one zip) by outcome", ["mode", "status", "client_ip", "session_id"])
errors_total = Counter("caption_errors_total", "Errors by exception type", ["mode", "error_type"])
images_skipped = Counter("caption_images_skipped_total", "Files in a zip that were skipped", ["reason"])
bytes_received = Counter("caption_bytes_received_total", "Uploaded bytes", ["mode", "client_ip"])
words_generated = Counter("caption_words_generated_total", "Words generated by the model", ["mode"])
zip_uploads = Counter("caption_zip_uploads_total", "Zip files uploaded", ["client_ip", "session_id"])
page_views = Counter("caption_page_views_total", "Streamlit script runs", ["client_ip", "session_id", "browser"])

# gauges
active_requests = Gauge("caption_active_requests", "Requests in progress", ["mode"])
bulk_queue_remaining = Gauge("caption_bulk_queue_remaining", "Images left in the running bulk job", ["session_id"])
last_inference_seconds = Gauge("caption_last_inference_seconds", "Inference time of the last image", ["mode", "client_ip"])
model_loaded = Gauge("caption_model_loaded", "1 if the model is loaded")
model_load_seconds = Gauge("caption_model_load_seconds", "Time taken to load the model")
model_parameters_bytes = Gauge("caption_model_parameters_bytes", "Size of the model weights")
active_sessions = Gauge("caption_active_sessions", "Sessions seen in the last 5 minutes")

_proc = psutil.Process(os.getpid())
process_rss = Gauge("caption_process_resident_memory_bytes", "RSS of the app process")
process_rss.set_function(lambda: _proc.memory_info().rss)
process_threads = Gauge("caption_process_threads", "Threads in the app process")
process_threads.set_function(lambda: _proc.num_threads())
process_cpu = Gauge("caption_process_cpu_percent", "CPU usage of the app process (100 = one core)")
process_cpu.set_function(lambda: _proc.cpu_percent(None))

# histograms
inference_latency = Histogram("caption_inference_latency_seconds", "Model inference time per image", ["mode"], buckets=(0.1, 0.25, 0.5, 0.75, 1, 1.5, 2, 3, 5, 8, 13, 20))
preprocess_latency = Histogram("caption_preprocess_latency_seconds", "Decode and resize time per image", ["mode"], buckets=(0.005, 0.01, 0.025, 0.05, 0.1, 0.25, 0.5, 1))
image_size_bytes = Histogram("caption_image_size_bytes", "Size of each image file", ["mode"], buckets=(10e3, 50e3, 100e3, 250e3, 500e3, 1e6, 2.5e6, 5e6, 10e6))
image_megapixels = Histogram("caption_image_megapixels", "Image resolution in megapixels", ["mode"], buckets=(0.1, 0.3, 0.5, 1, 2, 4, 8, 12, 24))
caption_length_words = Histogram("caption_length_words", "Words per caption", ["mode"], buckets=(2, 4, 6, 8, 10, 12, 15, 20, 30))
bulk_batch_size = Histogram("caption_bulk_batch_size_images", "Images per zip", buckets=(1, 2, 5, 10, 20, 50, 100, 200))

# summaries
request_duration = Summary("caption_request_duration_seconds", "End to end request time", ["mode"])
input_bytes = Summary("caption_input_bytes", "Upload size per request", ["mode"])
bulk_job_images = Summary("caption_bulk_job_images", "Images per bulk job")

build_info = Info("caption_app_build", "Build information")
build_info.info({"version": "1.0.0", "model": os.environ.get("CAPTION_MODEL", "Salesforce/blip-image-captioning-base"), "device": "cpu", "framework": "streamlit+transformers", "author": "kevin", "builddate": "October 2026"})

app_state = Enum("caption_app_state", "Current app state", states=["idle", "loading_model", "processing_single", "processing_bulk"])
app_state.state("idle")

_sessions = {}
_sessions_lock = threading.Lock()
SESSION_WINDOW = 300


def touch_session(session_id):
    now = time.time()
    with _sessions_lock:
        is_new = session_id not in _sessions
        _sessions[session_id] = now
        for sid, ts in list(_sessions.items()):
            if now - ts > SESSION_WINDOW:
                del _sessions[sid]
        active_sessions.set(len(_sessions))
    return is_new


def init_client_series(ip, session_id, browser):
    # create the series at 0 so rate()/increase() can see the first increment
    for mode in ("single", "bulk"):
        images_processed.labels(mode=mode, client_ip=ip, session_id=session_id, browser=browser)
        bytes_received.labels(mode=mode, client_ip=ip)
        for status in ("success", "partial", "error", "empty"):
            requests_total.labels(mode=mode, status=status, client_ip=ip, session_id=session_id)
    zip_uploads.labels(client_ip=ip, session_id=session_id)


for _mode in ("single", "bulk"):
    words_generated.labels(mode=_mode)
    active_requests.labels(mode=_mode)
    request_duration.labels(mode=_mode)
    input_bytes.labels(mode=_mode)
    inference_latency.labels(mode=_mode)
    preprocess_latency.labels(mode=_mode)
for _reason in ("not_an_image", "hidden_file", "corrupt_image", "over_limit", "zip_too_large"):
    images_skipped.labels(reason=_reason)

try:
    start_http_server(METRICS_PORT)
except OSError as e:
    print(f"WARNING: could not start metrics server on port {METRICS_PORT} ({e}). Is another instance running?", file=sys.stderr)
